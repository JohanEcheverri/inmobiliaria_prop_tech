package uniquindio.edu.co.inmobiliaria.models.enums;

/**
 * Estado comercial de un inmueble en el inventario.
 */
public enum Estado {
    
    /** Libre para oferta. */
    DISPONIBLE,
    /** Ya fue vendido. */
    VENDIDO,
    /** Actualmente arrendado. */
    ARRENDADO,
    /** Apartado o en proceso de cierre. */
    RESERVADO

}
